-- PostgreSQL schema used by the production profile.
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL, created_at TIMESTAMP(6), verified BOOLEAN NOT NULL DEFAULT FALSE,
  verification_code VARCHAR(6), verification_code_expiry TIMESTAMP(6),
  verification_attempts INTEGER NOT NULL DEFAULT 0, verification_last_sent_at TIMESTAMP(6)
);
CREATE TABLE projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL,
  description VARCHAR(2000), created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMP(6)
);
CREATE TABLE project_users (
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, PRIMARY KEY (project_id, user_id)
);
CREATE TABLE user_inputs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, raw_text TEXT NOT NULL,
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE, source VARCHAR(20), created_at TIMESTAMP(6)
);
CREATE TABLE records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(255) NOT NULL, description VARCHAR(4000),
  type VARCHAR(20) NOT NULL CHECK (type IN ('INCIDENCIA','PENDIENTE','AVANCE')),
  status VARCHAR(20) CHECK (status IN ('ABIERTA','CERRADA')),
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  related_record_id BIGINT REFERENCES records(id) ON DELETE SET NULL,
  created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
  source_input_id BIGINT REFERENCES user_inputs(id) ON DELETE SET NULL, structured_data JSONB
);
CREATE INDEX idx_records_project_id ON records(project_id);
CREATE TABLE record_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id BIGINT NOT NULL REFERENCES records(id) ON DELETE CASCADE,
  image_url VARCHAR(255) NOT NULL, created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);
